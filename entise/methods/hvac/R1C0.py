class R1C0(TypedViews, Method):
    """Implements the 1R0C model for HVAC demand and indoor temperature simulation.

    The 1R0C model calculates time-series data for indoor temperature and energy
    demand for heating and cooling based on provided inputs such as weather data, and the
    resistance property of buildings. It also summarizes total heating and
    cooling demands over the simulation period. This model is typically used for
    building energy performance analysis and HVAC load calculations.

    The zone has no thermal mass. In each interval it takes its free-running
    temperature ``T_out + gains / H``, where ``H`` is the conductance ``1 / R``
    plus ventilation. As in 1R1C, heating and cooling keep it between
    ``min_temperature[C]`` and ``max_temperature[C]``, within their power
    limits. Row 0 reports the initial temperature, ``init_temperature[C]`` or, if it
    is not given, ``min_temperature[C]``; it does not change the loads.

    Select the model for ``heating``, ``cooling`` or both, instead of ``hvac``,
    to get typed results from one solve. Each typed result has the indoor
    temperature and the columns and summary keys of its type. The control of a
    type the model is not selected for is off. A type-scoped control input,
    such as ``heating:power_heating[W]``, applies to its own control. ``hvac``
    and a typed key cannot select the same model on one object.

    Attributes:
        types (list): The types the method fills: ``hvac`` for the full result,
            and ``heating`` and ``cooling`` for the typed results.
        name (str): The name of the model.
        required_keys (list): Keys required in the input data for the model to
            execute, such as resistance, and weather data.
        optional_keys (list): Additional keys that are not mandatory but may be
            included in the input data, such as power heating, power cooling,
            or ventilation settings.
        required_data (list): Tables required to compute the outputs, such as
            weather data.
        optional_data (list): Optional tables, such as windows and internal
            and solar gains.
        output_summary (dict): Summary of the output results, providing keys with
            their descriptions, such as total heating and cooling demands.
        output_timeseries (dict): Time-series output data generated by the model,
            including indoor temperature, heating load, and cooling load.
    """

    types = [Types.HVAC, Types.HEATING, Types.COOLING]
    name = "1R0C"
    required_keys = [O.RESISTANCE, O.WEATHER]
    optional_keys = {
        O.TIMEZONE: None,
        O.POWER_HEATING: DEFAULT_POWER_HEATING,
        O.POWER_COOLING: DEFAULT_POWER_COOLING,
        O.ACTIVE_HEATING: DEFAULT_ACTIVE_HEATING,
        O.ACTIVE_COOLING: DEFAULT_ACTIVE_COOLING,
        # Row 0's indoor temperature; without it, the minimum (see calculate_timeseries_1r0c).
        O.TEMP_INIT: None,
        O.TEMP_MIN: DEFAULT_TEMP_MIN,
        O.TEMP_MAX: DEFAULT_TEMP_MAX,
        # Geometry, needed for ventilation given in air changes per hour
        O.AREA: Const.DEFAULT_AREA.value,
        O.HEIGHT: Const.DEFAULT_HEIGHT.value,
        O.GAINS_INTERNAL: None,
        O.GAINS_INTERNAL_COL: None,
        O.ACTIVE_VENTILATION: DEFAULT_ACTIVE_VENTILATION,
        O.VENTILATION: DEFAULT_VENTILATION,
        O.VENTILATION_COL: None,
        O.GAINS_SOLAR: None,
        O.WINDOWS: None,
        # Location, needed for solar gains through windows
        O.LAT: None,
        O.LON: None,
    }
    required_data = [O.WEATHER]
    optional_data = [O.WINDOWS, O.GAINS_INTERNAL, O.GAINS_SOLAR, O.VENTILATION]
    output_summary = {
        f"{Types.HEATING}{SEP}{C.DEMAND}[Wh]": "total heating demand",
        f"{Types.HEATING}{SEP}{O.LOAD_MAX}[W]": "maximum heating load",
        f"{Types.COOLING}{SEP}{C.DEMAND}[Wh]": "total cooling demand",
        f"{Types.COOLING}{SEP}{O.LOAD_MAX}[W]": "maximum cooling load",
    }
    output_timeseries = {
        f"{C.TEMP_IN}": "indoor air temperature",
        f"{Types.HEATING}{SEP}{C.LOAD}[W]": "heating load",
        f"{Types.COOLING}{SEP}{C.LOAD}[W]": "cooling load",
    }

    input_aliases = {"temp_init": O.TEMP_INIT, "temp_min": O.TEMP_MIN, "temp_max": O.TEMP_MAX}

    def generate(
        self,
        obj: dict | None = None,
        data: dict | None = None,
        results: dict | None = None,
        ts_type: str = Types.HVAC,
        **inputs,
    ) -> dict:
        """Generate HVAC time series based on input parameters and weather data.

        This method implements the abstract generate method from the Method base class.
        It processes the input parameters, calculates the indoor temperature and energy
        demand time series, and returns both the time series and summary statistics.

        Args:
            obj (dict, optional): Dictionary containing building parameters. Defaults to None.
            data (dict, optional): Dictionary containing input data. Defaults to None.
            ts_type (str, optional): Time series type to generate. Defaults to Types.HVAC.
            **inputs: Any input of the method, by its key or by its Python name (the key
                without its unit, such as ``area`` for ``area[m2]``). Keywords override the
                same keys in ``obj``. A table input, such as ``weather``, can be a
                DataFrame. For example:

                - ``resistance`` (``resistance[K W-1]``): Thermal resistance in K/W.
                - ``weather`` (DataFrame or str): Weather data with outdoor temperature.
                - ``power_heating`` and ``power_cooling`` (``[W]``): Maximum heating and cooling power in W.
                - ``active_heating`` and ``active_cooling`` (bool): Whether heating and cooling are active.
                - ``ventilation`` (``ventilation[W K-1]``): Ventilation rate in W/K.
                - ``active_ventilation`` (bool): Include ventilation heat loss. Defaults to True.
                - ``temp_min`` and ``temp_max`` (``min_temperature[C]``, ``max_temperature[C]``):
                  Minimum and maximum indoor temperature in °C.
                - ``temp_init`` (``init_temperature[C]``): Indoor temperature reported in row 0, in °C.
                  Defaults to the minimum temperature. Without thermal mass it does not change the loads.
                - ``gains_internal`` (``gains_internal[W]``): Internal heat gains in W.
                - ``gains_solar`` (``gains_solar[W]``): Solar heat gains in W.

        Returns:
            dict: Dictionary containing:
                - "summary" (dict): Summary statistics including total heating and
                  cooling demand, and maximum heating and cooling loads.
                - "timeseries" (pd.DataFrame): Time series of indoor temperature,
                  heating load, and cooling load with timestamps as index.

        Raises:
            Exception: If required data is missing or invalid.
        """
        obj, data = self._process_kwargs(obj, data, ts_type, **inputs)
        if ts_type in TYPED:
            return self.group_result(obj, data, results, ts_type)
        require_module("hvac-1r0c", "pvlib")
        # Read the tables once for this call; every helper below reuses this run.
        data = {**data, RUN_TIME_KEY: run_time(data)}
        obj, data = self._get_input_data(obj, data, ts_type)

        # Regular time step in seconds; each row is the interval [t, t + step).
        timestep = np.float32(step_seconds(data[O.WEATHER]))

        # Precompute auxiliary data
        data[O.GAINS_INTERNAL] = InternalGains().generate(obj, data)
        data[O.GAINS_SOLAR] = SolarGains().generate(obj, data)
        data[O.VENTILATION] = Ventilation().generate(obj, data)

        # Compute temperature and energy demand
        temp_in, p_heat, p_cool = calculate_timeseries_1r0c(obj, data, timestep)

        logger.debug(f"[HVAC R1C0] {ts_type}: max heating {p_heat.max()}, cooling {p_cool.max()}")

        return self._format_output(temp_in, p_heat, p_cool, obj, data, timestep)

    @staticmethod
    def _get_input_data(obj: dict, data: dict, method_type: str = Types.HVAC) -> tuple[dict, dict]:
        """Process and validate input data for HVAC calculation.

        This function extracts required and optional parameters from the input dictionaries,
        applies default values where needed, performs data validation, and prepares the
        data for HVAC calculation.

        Args:
            obj (dict): Dictionary containing building parameters such as thermal properties
                and temperature setpoints.
            data (dict): Dictionary containing input data such as weather information.
            method_type (str, optional): Method type to use for prefixing. Defaults to Types.HVAC.

        Returns:
            tuple: A tuple containing:
                - obj_out (dict): Processed object parameters with defaults applied.
                - data_out (dict): Processed data with required format for calculation.

        Notes:
            - Parameters can be specified with method-specific prefixes (e.g., "hvac:temp_min")
              which will take precedence over generic parameters (e.g., "temp_min").
        """
        obj_out = R1C0.get_relevant_objects(obj, method_type)
        run, weather_key, weather = hvac_weather(obj, data, method_type)
        windows = windows_table(obj, data, method_type)
        check_window_irradiance(run, weather_key, weather, obj, windows, method_type)
        internal_key = Method.get_with_method_backup(obj, O.GAINS_INTERNAL, method_type)
        internal_gains = Method.get_with_backup(data, internal_key) if isinstance(internal_key, str) else None
        ventilation_key = Method.get_with_method_backup(obj, O.VENTILATION, method_type)
        ventilation = Method.get_with_backup(data, ventilation_key) if isinstance(ventilation_key, str) else None
        data_out = {
            RUN_TIME_KEY: run,
            O.WEATHER: weather,
            O.WINDOWS: windows,
            internal_key: internal_gains,
            ventilation_key: ventilation,
        }

        # Clean up
        data_out = {k: v for k, v in data_out.items() if v is not None}

        return obj_out, data_out

    @staticmethod
    def _format_output(temp_in, p_heat, p_cool, obj, data, timestep) -> dict:
        # NB: use ndarray.max() (C-level, single pass over the buffer), not
        # builtins.max() which iterates 8760 elements as Python objects.
        summary = {
            f"{Types.HEATING}{SEP}{C.DEMAND}[Wh]": int(round(p_heat.sum() * timestep / 3600)),
            f"{Types.HEATING}{SEP}{O.LOAD_MAX}[W]": int(p_heat.max()),
            f"{Types.COOLING}{SEP}{C.DEMAND}[Wh]": int(round(p_cool.sum() * timestep / 3600)),
            f"{Types.COOLING}{SEP}{O.LOAD_MAX}[W]": int(p_cool.max()),
        }

        df = pd.DataFrame(
            {
                f"{C.TEMP_IN}": temp_in.round(3),
                f"{Types.HEATING}{SEP}{C.LOAD}[W]": p_heat.round().astype(int),
                f"{Types.COOLING}{SEP}{C.LOAD}[W]": p_cool.round().astype(int),
            },
            index=output_index(data[O.WEATHER].index, obj, data),
        )

        return {"summary": summary, "timeseries": df}


def calculate_timeseries_1r0c(
    obj: dict, data: dict, timestep: float | np.floating
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Calculate HVAC time series using a 1R0C model.

    The zone has a heat transfer coefficient ``H = 1 / R + H_ve`` and no thermal
    mass. Without heating or cooling it takes the free-running temperature
    ``T_free = T_out + (Q_solar + Q_internal) / H`` in every interval. As in the
    other RC models, heating and cooling keep the indoor temperature between
    ``min_temperature[C]`` and ``max_temperature[C]``:

    - below the minimum, heating supplies ``H * (T_min - T_free)``, up to its power limit;
    - above the maximum, cooling removes ``H * (T_free - T_max)``, up to its power limit;
    - in between, there is no load and the zone floats at ``T_free``.

    The indoor temperature is ``T_free + (P_heat - P_cool) / H``. As in the other RC
    models, row 0 reports the initial temperature, ``init_temperature[C]`` or, if it is
    not given, ``min_temperature[C]``. Without thermal mass it does not change the loads.

    Args:
        obj (dict): Building parameters: resistance, temperature limits, and
            heating and cooling switches and power limits.
        data (dict): Time series: weather, solar gains, internal gains and
            ventilation in W/K.
        timestep (float): The time step in seconds. Row t is the interval [t, t + step).

    Returns:
        tuple: A tuple containing:
            - temp_in (np.ndarray): Indoor temperature in each interval.
            - p_heat (np.ndarray): Mean heating power in each interval.
            - p_cool (np.ndarray): Mean cooling power in each interval.
    """
    temp_min = np.float32(obj[O.TEMP_MIN])
    temp_max = np.float32(obj[O.TEMP_MAX])

    weather = data[O.WEATHER]
    temp_air = weather[C.TEMP_AIR].to_numpy(dtype=np.float32, copy=False)
    solar_gains = data[O.GAINS_SOLAR].to_numpy(dtype=np.float32, copy=False).ravel()
    internal_gains = data[O.GAINS_INTERNAL].to_numpy(dtype=np.float32, copy=False).ravel()
    ventilation = data[O.VENTILATION].to_numpy(dtype=np.float32, copy=False).ravel()

    h_total = np.float32(1.0) / np.float32(obj[O.RESISTANCE]) + ventilation
    temp_free = temp_air + (solar_gains + internal_gains) / h_total

    zeros = np.zeros_like(temp_free)
    p_heat = zeros
    p_cool = zeros
    if bool(obj[O.ACTIVE_HEATING]):
        p_heat = np.minimum(np.maximum(h_total * (temp_min - temp_free), 0), np.float32(obj[O.POWER_HEATING]))
    if bool(obj[O.ACTIVE_COOLING]):
        p_cool = np.minimum(np.maximum(h_total * (temp_free - temp_max), 0), np.float32(obj[O.POWER_COOLING]))
    temp_in = temp_free + (p_heat - p_cool) / h_total
    if len(temp_in):
        initial = obj.get(O.TEMP_INIT)
        temp_in[0] = temp_min if initial is None else np.float32(initial)

    return temp_in.astype(np.float32), p_heat.astype(np.float32), p_cool.astype(np.float32)
